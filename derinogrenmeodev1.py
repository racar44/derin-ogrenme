import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Input
from sklearn.metrics import mean_squared_error, r2_score
import time
import os

# 1. ADIM: HOCANIN İSTEDİĞİ SABİT ÇEKİRDEK (OKUL NO SON 2 HANE: 05)
SEED = 5

# Grafiklerin kaydedileceği klasör
os.makedirs("odev_grafikleri", exist_ok=True)

# 2. ADIM: GİRİŞ VE HEDEF VERİSİNİ OLUŞTURMA
p = np.linspace(-2, 2, 500).reshape(-1, 1)
y_true = 1 + np.sin(np.pi * p / 4)

def deney_yap_ve_gorsellestir(tablo_adi, aktivasyon='tanh', ogrenme_orani=0.1, optimizer_tipi='sgd',
                             baslangic_dagilimi='normal', gizli_katman_sayisi=1, noron_sayisi=2):

    np.random.seed(SEED)
    tf.random.set_seed(SEED)

    model = Sequential()
    model.add(Input(shape=(1,)))

    model.add(Dense(noron_sayisi, activation=aktivasyon, kernel_initializer=baslangic_dagilimi))

    for _ in range(gizli_katman_sayisi - 1):
        model.add(Dense(noron_sayisi, activation=aktivasyon, kernel_initializer=baslangic_dagilimi))

    model.add(Dense(1, activation='linear', kernel_initializer=baslangic_dagilimi))

    if optimizer_tipi.lower() == 'sgd':
        opt = tf.keras.optimizers.SGD(learning_rate=ogrenme_orani)
    elif optimizer_tipi.lower() == 'rmsprop':
        opt = tf.keras.optimizers.RMSprop(learning_rate=ogrenme_orani)
    elif optimizer_tipi.lower() == 'adam':
        opt = tf.keras.optimizers.Adam(learning_rate=ogrenme_orani)

    model.compile(optimizer=opt, loss='mse')

    baslangic_suresi = time.time()
    history = model.fit(p, y_true, epochs=300, verbose=0)
    bitis_suresi = time.time()

    sure = bitis_suresi - baslangic_suresi
    y_pred = model.predict(p, verbose=0)

    mse = mean_squared_error(y_true, y_pred)
    r2 = r2_score(y_true, y_pred)

    # 3'lü Grafik Setini Çizme ve Kaydetme
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))

    # 1. Grafik: Epoch / MSE Error (Log)
    axes[0].plot(history.history['loss'], color='firebrick', linewidth=2)
    axes[0].set_yscale('log')
    axes[0].set_title(f"{tablo_adi}: Kayıp (Logaritmik)")
    axes[0].set_xlabel("epoch")
    axes[0].set_ylabel("loss L = 1/2(t - a^2)^2")
    axes[0].grid(True, which="both", linestyle="--", alpha=0.4)

    # 2. Grafik: Hedef ve Ağ Çıkışı
    axes[1].plot(p, y_true, label="Hedef", color="#1f4e79", linewidth=2)
    axes[1].plot(p, y_pred, label="Ağ çıkışı", color="firebrick", linewidth=2)
    axes[1].set_title(f"{tablo_adi}: Hedef ve Ağ Çıkışı")
    axes[1].set_xlabel("p (giriş)")
    axes[1].set_ylabel("a^2 (çıkış)")
    axes[1].legend()
    axes[1].grid(True, linestyle="--", alpha=0.4)

    # 3. Grafik: R2 Dağılımı
    axes[2].scatter(y_true, y_pred, alpha=0.5, color='firebrick', s=15)
    axes[2].plot([y_true.min(), y_true.max()], [y_true.min(), y_true.max()], 'r--', linewidth=1.5)
    axes[2].set_title(f"{tablo_adi}: R2 Grafiği (R2 = {r2:.4f})")
    axes[2].set_xlabel("Gerçek Değerler (Hedef)")
    axes[2].set_ylabel("Tahmin Edilen Değerler")
    axes[2].grid(True, linestyle="--", alpha=0.4)

    plt.tight_layout()
    dosya_adi = f"odev_grafikleri/{tablo_adi.lower().replace(' ', '_').replace(':', '')}.png"
    plt.savefig(dosya_adi, dpi=300)
    plt.close()

    print(f"[{tablo_adi}] Tamamlandı -> MSE: {mse:.5f}, R2: {r2:.5f}, Süre: {sure:.2f}sn (Grafik kaydedildi: {dosya_adi})")
    return mse, r2, sure

# --- TABLO 1 DENEYLERİ ---
print("\n=== TABLO 1: AKTİVASYON FONKSİYONLARI ===")
aktivasyonlar = ['linear', 'sigmoid', 'tanh', 'relu', 'leaky_relu', 'elu', 'swish']
gorunen_isimler = ['Lineer', 'Sigmoid', 'Hiperbolik Tanjant', 'ReLU', 'LeakyReLU', 'ELU', 'SiLU']

for act, isim in zip(aktivasyonlar, gorunen_isimler):
    deney_yap_ve_gorsellestir(f"Tablo1_{isim}", aktivasyon=act, ogrenme_orani=0.1, optimizer_tipi='sgd',
                              baslangic_dagilimi='normal', gizli_katman_sayisi=1, noron_sayisi=2)

# --- TABLO 2 DENEYLERİ ---
print("\n=== TABLO 2: ÖĞRENME ORANI ===")
for lr in [0.1, 0.01, 0.001]:
    deney_yap_ve_gorsellestir(f"Tablo2_LR_{str(lr).replace('.', '_')}", aktivasyon='tanh', ogrenme_orani=lr, optimizer_tipi='sgd',
                              baslangic_dagilimi='normal', gizli_katman_sayisi=1, noron_sayisi=2)

# --- TABLO 3 DENEYLERİ ---
print("\n=== TABLO 3: OPTİMİZATÖR ===")
for opt in ['sgd', 'rmsprop', 'adam']:
    deney_yap_ve_gorsellestir(f"Tablo3_{opt.upper()}", aktivasyon='tanh', ogrenme_orani=0.1, optimizer_tipi=opt,
                              baslangic_dagilimi='normal', gizli_katman_sayisi=1, noron_sayisi=2)

# --- TABLO 4 DENEYLERİ ---
print("\n=== TABLO 4: BAŞLANGIÇ DAĞILIMI ===")
for dagilim in ['normal', 'uniform']:
    deney_yap_ve_gorsellestir(f"Tablo4_{dagilim.capitalize()}", aktivasyon='tanh', ogrenme_orani=0.1, optimizer_tipi='sgd',
                              baslangic_dagilimi=dagilim, gizli_katman_sayisi=1, noron_sayisi=2)

# --- TABLO 5 DENEYLERİ ---
print("\n=== TABLO 5: KATMAN SAYISI ===")
for katman in [1, 2, 5, 10, 20]:
    deney_yap_ve_gorsellestir(f"Tablo5_Katman_{katman}", aktivasyon='tanh', ogrenme_orani=0.1, optimizer_tipi='sgd',
                              baslangic_dagilimi='normal', gizli_katman_sayisi=katman, noron_sayisi=2)

# --- TABLO 6 DENEYLERİ ---
print("\n=== TABLO 6: NÖRON SAYISI ===")
for noron in [2, 5, 10, 20, 50]:
    deney_yap_ve_gorsellestir(f"Tablo6_Noron_{noron}", aktivasyon='tanh', ogrenme_orani=0.1, optimizer_tipi='sgd',
                              baslangic_dagilimi='normal', gizli_katman_sayisi=1, noron_sayisi=noron)

print("\nTüm deneyler bitti ve grafikler 'odev_grafikleri' klasörüne kaydedildi!")